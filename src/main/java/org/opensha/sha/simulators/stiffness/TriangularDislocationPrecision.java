	/** Difference of the two endpoint corrections, in the edge's angular coordinates. */
	static double[] edge(double[] observation, double[] slip, double[] start, double[] end, double poisson) {
		BigDecimal sx = subtract(value(end[0]), value(start[0]));
		BigDecimal sy = subtract(value(end[1]), value(start[1]));
		BigDecimal sz = subtract(value(end[2]), value(start[2]));
		BigDecimal horizontal = sqrt(add(multiply(sx, sx), multiply(sy, sy)));
		BigDecimal length = sqrt(add(multiply(horizontal, horizontal), multiply(sz, sz)));
		BigDecimal dx = subtract(value(observation[0]), value(start[0]));
		BigDecimal dy = subtract(value(observation[1]), value(start[1]));
		BigDecimal dz = subtract(value(start[2]), value(observation[2]));
		BigDecimal y1 = divide(add(multiply(sx, dx), multiply(sy, dy)), horizontal);
		BigDecimal y2 = divide(subtract(multiply(sy, dx), multiply(sx, dy)), horizontal);
		BigDecimal b1 = divide(add(multiply(sx, value(slip[0])), multiply(sy, value(slip[1]))), horizontal);
		BigDecimal b2 = divide(subtract(multiply(sy, value(slip[0])), multiply(sx, value(slip[1]))), horizontal);
		BigDecimal b3 = value(-slip[2]);
		BigDecimal sinB = divide(horizontal, length), cosB = divide(negate(sz), length);
		if (y1.signum() >= 0) {
			sinB = negate(sinB);
			cosB = negate(cosB);
		}
		BigDecimal[] first = strain(y1, y2, dz, sinB, cosB, b1, b2, b3, value(poisson), value(-start[2]));
		BigDecimal[] second = strain(subtract(y1, horizontal), y2, add(dz, sz), sinB, cosB,
				b1, b2, b3, value(poisson), value(-end[2]));
		double[] result = new double[6];
		for (int i = 0; i < 6; i++)
			result[i] = subtract(second[i], first[i]).doubleValue();
		return result;
	}

